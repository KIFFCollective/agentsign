// Package signers reads and writes ssh-keygen allowed_signers files
// (see ssh-keygen(1), "ALLOWED SIGNERS").
//
// agentsign writes one line per active agent:
//
//	<email> namespaces="git" <keytype> <base64>
//
// and a marker comment for each revoked agent, so verification still knows
// the email belongs to an agent (and rejects it) rather than treating it as a
// human:
//
//	# agentsign-revoked: <email>
package signers

import (
	"bufio"
	"fmt"
	"io"
	"sort"
	"strings"
)

// RevokedMarker prefixes revoked-agent comment lines.
const RevokedMarker = "# agentsign-revoked: "

// Entry is one allowed_signers line.
type Entry struct {
	Principals []string
	Options    string // raw options field, e.g. `namespaces="git"`
	KeyType    string
	Key        string // base64 blob
	Comment    string // written as a "#" line above the entry
}

// File is a parsed allowed_signers file.
type File struct {
	Entries []Entry
	Revoked []string
}

// AgentEmails returns every email that belongs to an agent, active or
// revoked, lower-cased.
func (f *File) AgentEmails() map[string]bool {
	out := map[string]bool{}
	for _, e := range f.Entries {
		for _, p := range e.Principals {
			out[strings.ToLower(p)] = true
		}
	}
	for _, r := range f.Revoked {
		out[strings.ToLower(r)] = true
	}
	return out
}

// IsRevoked reports whether email is marked revoked.
func (f *File) IsRevoked(email string) bool {
	for _, r := range f.Revoked {
		if strings.EqualFold(r, email) {
			return true
		}
	}
	return false
}

// Format renders the file deterministically (entries sorted by first principal).
func Format(f *File) []byte {
	entries := append([]Entry(nil), f.Entries...)
	sort.SliceStable(entries, func(i, j int) bool { return first(entries[i]) < first(entries[j]) })
	revoked := append([]string(nil), f.Revoked...)
	sort.Strings(revoked)

	var b strings.Builder
	b.WriteString("# Generated by agentsign. Do not edit by hand; run `agentsign signers`.\n")
	for _, e := range entries {
		if e.Comment != "" {
			fmt.Fprintf(&b, "# %s\n", oneLine(e.Comment))
		}
		b.WriteString(strings.Join(e.Principals, ","))
		if e.Options != "" {
			b.WriteString(" " + e.Options)
		}
		fmt.Fprintf(&b, " %s %s\n", e.KeyType, e.Key)
	}
	for _, r := range revoked {
		b.WriteString(RevokedMarker + r + "\n")
	}
	return []byte(b.String())
}

func first(e Entry) string {
	if len(e.Principals) == 0 {
		return ""
	}
	return strings.ToLower(e.Principals[0])
}

func oneLine(s string) string { return strings.NewReplacer("\n", " ", "\r", " ").Replace(s) }

// Parse reads an allowed_signers file. Lines it can't parse are an error, so
// a corrupt file never silently drops an agent.
func Parse(r io.Reader) (*File, error) {
	f := &File{}
	sc := bufio.NewScanner(r)
	var pending string
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		switch {
		case line == "":
			pending = ""
			continue
		case strings.HasPrefix(line, RevokedMarker):
			f.Revoked = append(f.Revoked, strings.TrimSpace(strings.TrimPrefix(line, RevokedMarker)))
			continue
		case strings.HasPrefix(line, "#"):
			pending = strings.TrimSpace(strings.TrimPrefix(line, "#"))
			continue
		}
		e, err := parseLine(line)
		if err != nil {
			return nil, fmt.Errorf("allowed_signers line %d: %w", n, err)
		}
		e.Comment = pending
		pending = ""
		f.Entries = append(f.Entries, e)
	}
	return f, sc.Err()
}

func parseLine(line string) (Entry, error) {
	fields, err := split(line)
	if err != nil {
		return Entry{}, err
	}
	if len(fields) < 3 {
		return Entry{}, fmt.Errorf("want principals [options] keytype key")
	}
	e := Entry{Principals: strings.Split(fields[0], ",")}
	rest := fields[1:]
	if !isKeyType(rest[0]) {
		e.Options = rest[0]
		rest = rest[1:]
	}
	if len(rest) < 2 || !isKeyType(rest[0]) {
		return Entry{}, fmt.Errorf("missing key type")
	}
	e.KeyType, e.Key = rest[0], rest[1]
	return e, nil
}

func isKeyType(s string) bool {
	return strings.HasPrefix(s, "ssh-") || strings.HasPrefix(s, "ecdsa-") || strings.HasPrefix(s, "sk-")
}

// split breaks a line on whitespace, keeping double-quoted runs together.
func split(line string) ([]string, error) {
	var out []string
	var cur strings.Builder
	inQuote := false
	for _, r := range line {
		switch {
		case r == '"':
			inQuote = !inQuote
			cur.WriteRune(r)
		case (r == ' ' || r == '\t') && !inQuote:
			if cur.Len() > 0 {
				out = append(out, cur.String())
				cur.Reset()
			}
		default:
			cur.WriteRune(r)
		}
	}
	if inQuote {
		return nil, fmt.Errorf("unterminated quote")
	}
	if cur.Len() > 0 {
		out = append(out, cur.String())
	}
	return out, nil
}

// EntryFromPublicKey builds an entry from an authorized_keys style line
// ("<type> <base64> [comment]").
func EntryFromPublicKey(email, pubkey, comment string) (Entry, error) {
	parts := strings.Fields(pubkey)
	if len(parts) < 2 || !isKeyType(parts[0]) {
		return Entry{}, fmt.Errorf("not a public key: %q", pubkey)
	}
	return Entry{
		Principals: []string{email},
		Options:    `namespaces="git"`,
		KeyType:    parts[0],
		Key:        parts[1],
		Comment:    comment,
	}, nil
}
